/* @vitest-environment jsdom */
import {cleanup, fireEvent, render, screen, waitFor} from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import {QueryClient, QueryClientProvider} from "@tanstack/react-query";
import {afterEach, expect, it, vi} from "vitest";
vi.mock("@tauri-apps/api/core", () => import("../../../demo/mock/core"));
import ManualTimeBlockDialog from "./ManualTimeBlockDialog.tsx";
import {ToastProvider} from "../../Componants/Toast.tsx";
import {invoke} from "../../../demo/mock/core";
afterEach(cleanup);
it("saves the clicked calendar time as manual tracking with notes and a project", async () => {
    const user = userEvent.setup();
    const projectId = await invoke<number>("create_manual_project", {name: "Calendar click test"});
    const start = new Date(2026, 9, 12, 10, 30);
    const close = vi.fn();
    const client = new QueryClient({defaultOptions: {queries: {retry: false}}});
    render(<QueryClientProvider client={client}><ToastProvider><ManualTimeBlockDialog open initialStart={start} anchor={null} onClose={close}/></ToastProvider></QueryClientProvider>);
    const startInput = screen.getByLabelText("Start") as HTMLInputElement;
    expect(new Date(startInput.value).getTime()).toBe(start.getTime());
    expect(new Date((screen.getByLabelText("End") as HTMLInputElement).value).getTime()).toBe(start.getTime() + 3600000);
    await user.type(screen.getByLabelText("Name (optional)"), "Calendar entry");
    await user.type(screen.getByLabelText("Description or notes"), "From calendar");
    await waitFor(() => expect((screen.getByRole("button", {name: "Category"}) as HTMLButtonElement).disabled).toBe(false));
    await user.click(screen.getByRole("button", {name: "Category"}));
    await user.click(await screen.findByRole("option", {name: "Calendar click test"}));
    fireEvent.change(screen.getByLabelText("End"), {target: {value: startInput.value}});
    await user.click(screen.getByRole("button", {name: "Save"}));
    expect(screen.getByText("End time must be after start time.")).toBeTruthy();
    fireEvent.change(screen.getByLabelText("End"), {target: {value: "2026-10-12T11:30"}});
    await user.click(screen.getByRole("button", {name: "Save"}));
    await waitFor(() => expect(close).toHaveBeenCalledOnce());
    const blocks = await invoke<Array<{id: number}>>("get_manual_time_blocks", {rangeStart: start.getTime()/1000, rangeEnd: start.getTime()/1000+3601});
    expect(blocks).toContainEqual(expect.objectContaining({title: "Calendar entry", notes: "From calendar", project_id: projectId, start_time: start.getTime()/1000, end_time: start.getTime()/1000+3600}));
    for (const block of blocks) await invoke("delete_manual_time_block", {id: block.id});
    await invoke("delete_manual_project", {id: projectId});
    client.clear();
});

it("keeps title, project and notes while the future draft is moved or resized", async () => {
    const user = userEvent.setup();
    const client = new QueryClient({defaultOptions: {queries: {retry: false}}});
    const projectId = await invoke<number>("create_manual_project", {name: "Planned work"});
    const start = new Date(Date.now() + 14 * 86400000);
    start.setHours(10, 0, 0, 0);
    const preview = vi.fn();
    const close = vi.fn();
    const wrapper = ({children}: {children: React.ReactNode}) => <QueryClientProvider client={client}><ToastProvider>{children}</ToastProvider></QueryClientProvider>;
    const view = render(<ManualTimeBlockDialog open initialStart={start} initialEnd={new Date(start.getTime()+7200000)} anchor={null} onClose={close} onPreviewChange={preview}/>, {wrapper});
    await user.type(screen.getByLabelText("Name (optional)"), "Planning");
    await user.type(screen.getByLabelText("Description or notes"), "Keep these notes");
    await waitFor(() => expect((screen.getByRole("button", {name: "Category"}) as HTMLButtonElement).disabled).toBe(false));
    await user.click(screen.getByRole("button", {name: "Category"}));
    await user.click(await screen.findByRole("option", {name: "Planned work"}));
    const moved = new Date(start.getTime() + 86400000);
    const resized = new Date(moved.getTime() + 10800000);
    view.rerender(<ManualTimeBlockDialog open initialStart={moved} initialEnd={resized} anchor={null} onClose={close} onPreviewChange={preview}/>);
    expect((screen.getByLabelText("Name (optional)") as HTMLInputElement).value).toBe("Planning");
    expect((screen.getByLabelText("Description or notes") as HTMLTextAreaElement).value).toBe("Keep these notes");
    expect(new Date((screen.getByLabelText("Start") as HTMLInputElement).value).getTime()).toBe(moved.getTime());
    await waitFor(() => expect(preview).toHaveBeenLastCalledWith({start:moved, end:resized, title:"Planning"}));
    await user.click(screen.getByRole("button", {name: "Save"}));
    await waitFor(() => expect(close).toHaveBeenCalledOnce());
    const blocks = await invoke<Array<{id:number}>>("get_manual_time_blocks", {rangeStart:moved.getTime()/1000, rangeEnd:resized.getTime()/1000+1});
    expect(blocks).toContainEqual(expect.objectContaining({title:"Planning", notes:"Keep these notes", project_id:projectId, start_time:moved.getTime()/1000, end_time:resized.getTime()/1000}));
    for (const block of blocks) await invoke("delete_manual_time_block", {id:block.id});
    await invoke("delete_manual_project", {id:projectId});
    client.clear();
});
