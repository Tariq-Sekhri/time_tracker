const ROUNDING_MODE_LABEL = {nearest: "Rounded to nearest", up: "Rounded up to", down: "Rounded down to"} as const;

export function reportTitle(ctx: Ctx): string {
    return pdfLine(ctx.options.pdf.title) || "Time report";
}

export function reportRange(ctx: Ctx): string {
    return pdfLine(rangeLabel(ctx.model.rangeStart, ctx.model.rangeEnd));
}

/* ------------------------------------------------------------------ header */

export function drawCoverHeader(ctx: Ctx, generatedAt: number) {
    const {doc, theme, options} = ctx;
    const left = ctx.margin.left;
    const right = ctx.pageWidth - ctx.margin.right;

    fill(ctx, theme.accent);
    doc.rect(0, 0, ctx.pageWidth, 5, "F");

    let y = 44;
    const preparedBy = pdfLine(options.pdf.preparedBy);
    eyebrow(ctx, fit(ctx, preparedBy || "Time report", ctx.contentWidth * 0.6), left, y, preparedBy ? theme.accentInk : INK.muted, 7.5);
    font(ctx, 7.5, "normal", INK.muted);
    doc.text(`Generated ${longDate(generatedAt)}`, right, y, {align: "right"});

    y += 30;
    font(ctx, 22, "bold");
    const titleLines = (doc.splitTextToSize(reportTitle(ctx), ctx.contentWidth) as string[]).slice(0, 3);
    doc.text(titleLines, left, y, {lineHeightFactor: 1.12});
    y += (titleLines.length - 1) * 22 * 1.12 + 26;

    // Invoice-style meta columns.
    const meta: [string, string][] = [];
    const preparedFor = pdfLine(options.pdf.preparedFor);
    if (preparedFor) meta.push(["Prepared for", preparedFor]);
    meta.push(["Period", reportRange(ctx)]);
    if (options.rounding) meta.push(["Rounding", `${ROUNDING_MODE_LABEL[options.roundingMode]} ${options.rounding} min`]);
    if (ctx.model.totals.total > 0) meta.push(["Total time", humanDuration(ctx.model.totals.total)]);
    const columnWidth = ctx.contentWidth / Math.max(meta.length, 3);
    meta.forEach(([label, value], index) => {
        const x = left + index * columnWidth;
        eyebrow(ctx, label, x, y);
        font(ctx, 9.5, index === 0 && preparedFor ? "bold" : "normal");
        doc.text(fit(ctx, value, columnWidth - 14), x, y + 14);
    });
    y += 30;
    hairline(ctx, left, y, right);
    ctx.y = y + 22;
}

/** Running header (pages 2+) and footer (all pages). Runs after layout so totals are known. */
export function drawPageChrome(ctx: Ctx, appVersion: string) {
    const {doc} = ctx;
    const pages = doc.getNumberOfPages();
    const left = ctx.margin.left;
    const right = ctx.pageWidth - ctx.margin.right;
    for (let page = 1; page <= pages; page++) {
        doc.setPage(page);
        if (page > 1) {
            fill(ctx, ctx.theme.accent);
            doc.rect(0, 0, ctx.pageWidth, 2.5, "F");
            const range = reportRange(ctx);
            font(ctx, 7.5, "normal", INK.muted);
            const rangeWidth = width(ctx, range);
            doc.text(range, right, 30, {align: "right"});
            font(ctx, 7.5, "bold", INK.secondary);
            doc.text(fit(ctx, reportTitle(ctx), ctx.contentWidth - rangeWidth - 24), left, 30);
            hairline(ctx, left, 38, right);
        }
        const footerY = ctx.pageHeight - 26;
        font(ctx, 7, "normal", INK.faint);
        doc.text(`Generated by Time Tracker${appVersion ? ` ${pdfLine(appVersion)}` : ""}`, left, footerY);
        doc.text(`Page ${page} of ${pages}`, right, footerY, {align: "right"});
    }
}

/* ---------------------------------------------------------------- overview */

export function drawOverview(ctx: Ctx) {
    const {doc, model, theme} = ctx;
    const {totals} = model;
    type Tile = {label: string; value: string; note: string; highlight?: boolean};
    const tiles: Tile[] = [
        {
            label: "Total time",
            value: humanDuration(totals.total),
            note: `${formatDuration(totals.total, "decimal")} hours`,
            highlight: true,
        },
    ];
    if (model.hasManual) {
        tiles.push({
            label: "Manual time",
            value: humanDuration(totals.manual),
            note: `${totals.manualEntries} ${totals.manualEntries === 1 ? "entry" : "entries"}${model.hasActivity ? ` · ${percent(totals.manual, totals.total)}` : ""}`,
        });
    }
    if (model.hasActivity) {
        const noun = model.activitySource === "logs" ? "log rows" : totals.activityItems === 1 ? "session" : "sessions";
        tiles.push({
            label: "Tracked activity",
            value: humanDuration(totals.activity),
            note: `${totals.activityItems} ${noun}${model.hasManual ? ` · ${percent(totals.activity, totals.total)}` : ""}`,
        });
    }
    tiles.push({label: "Active days", value: String(totals.activeDays), note: `of ${totals.rangeDays} ${totals.rangeDays === 1 ? "day" : "days"} in range`});
    tiles.push({label: "Daily average", value: humanDuration(totals.dailyAverage), note: "per active day"});

    const gap = 10;
    const height = 60;
    ensureSpace(ctx, height + 10);
    const tileWidth = (ctx.contentWidth - gap * (tiles.length - 1)) / tiles.length;
    tiles.forEach((tile, index) => {
        const x = ctx.margin.left + index * (tileWidth + gap);
        fill(ctx, tile.highlight ? theme.accentWash : SURFACE.tile);
        doc.roundedRect(x, ctx.y, tileWidth, height, 5, 5, "F");
        if (tile.highlight) {
            fill(ctx, theme.accent);
            roundedBar(ctx, x, ctx.y, 3, height, 0, "right");
        }
        const pad = 12;
        eyebrow(ctx, fit(ctx, tile.label, tileWidth - pad * 2), x + pad, ctx.y + 17, tile.highlight ? theme.accentInk : INK.muted);
        font(ctx, fitFontSize(ctx, tile.value, tileWidth - pad * 2, 16, 10), "bold");
        doc.text(fit(ctx, tile.value, tileWidth - pad * 2), x + pad, ctx.y + 38);
        font(ctx, 7, "normal", INK.muted);
        doc.text(fit(ctx, tile.note, tileWidth - pad * 2), x + pad, ctx.y + 51);
    });
    ctx.y += height;
}

/* ------------------------------------------------------- category breakdown */

export function drawCategoryBreakdown(ctx: Ctx) {
    const {doc, model} = ctx;
    const bars = model.chart;
    if (!bars.length) return;
    const total = model.totals.total;
    const rowHeight = 19;
    const barHeight = 9;
    sectionHeading(ctx, "Time by category", `${model.categories.filter(c => c.seconds > 0).length} categories`, Math.min(bars.length, 4) * rowHeight);

    const left = ctx.margin.left;
    const right = ctx.pageWidth - ctx.margin.right;
    const labelWidth = Math.min(170, ctx.contentWidth * 0.3);
    const valueWidth = 96;
    const barX = left + labelWidth + 10;
    const barMax = right - valueWidth - barX;
    const longest = Math.max(...bars.map(b => b.seconds), 1);

    for (const bar of bars) {
        ensureSpace(ctx, rowHeight);
        const mid = ctx.y + rowHeight / 2;
        font(ctx, 8.5, "normal", bar.other ? INK.muted : INK.primary);
        doc.text(fit(ctx, pdfLine(bar.label), labelWidth), left, mid + 3);

        fill(ctx, SURFACE.track);
        doc.roundedRect(barX, mid - barHeight / 2, barMax, barHeight, 2, 2, "F");
        fill(ctx, bar.color);
        roundedBar(ctx, barX, mid - barHeight / 2, Math.max(2.5, (bar.seconds / longest) * barMax), barHeight, 2.5, "right");

        font(ctx, 8.5, "bold");
        doc.text(humanDuration(bar.seconds), right - 38, mid + 3, {align: "right"});
        font(ctx, 8, "normal", INK.muted);
        doc.text(percent(bar.seconds, total), right, mid + 3, {align: "right"});
        ctx.y += rowHeight;
    }

    ctx.y += 14;
    drawCategoryTable(ctx);
}

function drawCategoryTable(ctx: Ctx) {
    const {model, options} = ctx;
    const both = model.hasManual && model.hasActivity;
    const total = model.totals.total;
    const fmt = (s: number) => formatDuration(s, options.durationFormat);
    type Meta = {color: Rgb; child: boolean};
    const meta: Meta[] = [];
    const body: string[][] = [];
    const push = (stat: CategoryStat, child: boolean) => {
        if (stat.seconds <= 0 && stat.entries === 0) return;
        meta.push({color: stat.color, child});
        const row = [pdfLine(stat.name)];
        if (both) row.push(child ? "" : stat.type === "manual" ? "Manual" : "Activity");
        row.push(String(stat.entries), fmt(stat.seconds), percent(stat.seconds, total));
        body.push(row);
    };
    for (const stat of model.categories) {
        push(stat, false);
        for (const child of stat.children) push(child, true);
    }
    const head = ["Category", ...(both ? ["Type"] : []), model.activitySource === "logs" && !model.hasManual ? "Rows" : "Entries", "Time", "Share"];
    const numeric = new Set([head.length - 3, head.length - 2, head.length - 1]);
    const style = tableStyle(ctx);
    ctx.autoTable(ctx.doc, {
        ...style,
        startY: ctx.y,
        head: [head.map(h => h.toUpperCase())],
        body,
        foot: [["Total", ...(both ? [""] : []), String(model.totals.manualEntries + model.totals.activityItems), fmt(total), total ? "100%" : "0%"]],
        columnStyles: {
            0: {cellWidth: "auto"},
            ...(both ? {1: {cellWidth: 62}} : {}),
            [head.length - 3]: {cellWidth: 52},
            [head.length - 2]: {cellWidth: 64},
            [head.length - 1]: {cellWidth: 48},
        },
        didParseCell: data => {
            if (numeric.has(data.column.index)) data.cell.styles.halign = "right";
            if (data.column.index === 0) data.cell.styles.cellPadding = {top: 4.6, bottom: 4.6, left: data.section === "body" ? (meta[data.row.index]?.child ? 30 : 20) : 6, right: 6};
            if (data.section === "body") {
                const m = meta[data.row.index];
                data.cell.styles.fillColor = m.child ? false : SURFACE.zebra;
                if (m.child) data.cell.styles.textColor = INK.secondary;
                if (!m.child && data.column.index === 0) data.cell.styles.fontStyle = "bold";
            }
            if (data.section === "body" && data.column.index === 1 && both) data.cell.styles.textColor = INK.muted;
        },
        didDrawCell: data => {
            if (data.section !== "body" || data.column.index !== 0) return;
            const m = meta[data.row.index];
            fill(ctx, m.color);
            const cy = data.cell.y + 4.6 + 3.4;
            if (m.child) ctx.doc.circle(data.cell.x + 22, cy, 2, "F");
            else ctx.doc.roundedRect(data.cell.x + 7, cy - 3.5, 7, 7, 1.5, 1.5, "F");
        },
    });
    afterTable(ctx);
}

/* ---------------------------------------------------------- daily breakdown */

const BUCKET_NOUN = {day: "day", week: "week", month: "month"} as const;

export function drawDailyBreakdown(ctx: Ctx) {
    const {doc, model, theme, options} = ctx;
    const buckets = model.buckets;
    if (!buckets.length) return;
    const unit = model.bucketUnit;
    const both = model.hasManual && model.hasActivity;
    const manualColor = theme.accent;
    const activityColor = model.hasManual ? theme.secondary : theme.accent;
    const note =
        unit === "day"
            ? ""
            : unit === "week"
              ? "Grouped by week (range is longer than 62 days)"
              : "Grouped by month (range is longer than two years)";

    const plotHeight = 132;
    const axisWidth = 30;
    const legendHeight = both ? 16 : 0;
    sectionHeading(ctx, `Time by ${BUCKET_NOUN[unit]}`, note, plotHeight + legendHeight + 30);

    const left = ctx.margin.left;
    const right = ctx.pageWidth - ctx.margin.right;

    if (both) {
        const items: [string, Rgb][] = [
            ["Manual", manualColor],
            ["Activity", activityColor],
        ];
        let x = right;
        font(ctx, 7.5, "normal", INK.secondary);
        for (const [label, color] of [...items].reverse()) {
            x -= width(ctx, label);
            doc.text(label, x, ctx.y + 6);
            x -= 11;
            fill(ctx, color);
            doc.roundedRect(x, ctx.y + 0.5, 7, 7, 1.5, 1.5, "F");
            x -= 14;
        }
        ctx.y += legendHeight;
    }

    const top = ctx.y + 4;
    const bottom = top + plotHeight;
    const plotLeft = left + axisWidth;
    const plotWidth = right - plotLeft;
    const max = Math.max(...buckets.map(b => b.manual + b.activity), 0);
    const {step, ticks} = hourTicks(max);
    const scaleMax = step * ticks;
    const yOf = (seconds: number) => bottom - (seconds / scaleMax) * plotHeight;
    const slot = plotWidth / buckets.length;

    // Weekend shading behind everything.
    fill(ctx, SURFACE.weekend);
    buckets.forEach((bucket, index) => {
        if (bucket.weekend) doc.rect(plotLeft + index * slot, top, slot, plotHeight, "F");
    });

    for (let i = 0; i <= ticks; i++) {
        const value = step * i;
        const y = yOf(value);
        hairline(ctx, plotLeft, y, right, i === 0 ? INK.faint : SURFACE.grid, i === 0 ? 0.7 : 0.5);
        font(ctx, 6.8, "normal", INK.muted);
        doc.text(tickLabel(value), plotLeft - 6, y + 2.4, {align: "right"});
    }

    const barWidth = Math.max(1.5, Math.min(18, slot * 0.62));
    const gap = 0.8;
    buckets.forEach((bucket, index) => {
        const x = plotLeft + index * slot + (slot - barWidth) / 2;
        const manualHeight = (bucket.manual / scaleMax) * plotHeight;
        const activityHeight = (bucket.activity / scaleMax) * plotHeight;
        const radius = Math.min(2.5, barWidth / 3);
        if (manualHeight > 0.2) {
            fill(ctx, manualColor);
            if (activityHeight > 0.2) doc.rect(x, bottom - manualHeight, barWidth, manualHeight, "F");
            else roundedBar(ctx, x, bottom - manualHeight, barWidth, manualHeight, radius, "top");
        }
        if (activityHeight > 0.2) {
            fill(ctx, activityColor);
            const lift = manualHeight > 0.2 ? manualHeight + gap : 0;
            roundedBar(ctx, x, bottom - lift - activityHeight, barWidth, activityHeight, radius, "top");
        }
    });

    // X labels, thinned to avoid collisions.
    font(ctx, 6.8, "normal", INK.muted);
    const labels = buckets.map((bucket, index) => bucketAxisLabel(bucket, unit, index, buckets));
    const widest = Math.max(...labels.map(label => width(ctx, label)));
    const every = Math.max(1, Math.ceil((widest + 8) / slot));
    labels.forEach((label, index) => {
        if (index % every !== 0) return;
        const cx = plotLeft + index * slot + slot / 2;
        doc.text(label, Math.min(Math.max(cx, plotLeft + width(ctx, label) / 2), right - width(ctx, label) / 2), bottom + 11, {align: "center"});
    });
    ctx.y = bottom + 18;

    drawDailyTable(ctx);
    void options;
}

function bucketAxisLabel(bucket: TimeBucket, unit: "day" | "week" | "month", index: number, all: TimeBucket[]): string {
    if (unit === "month") return monthYear(bucket.start).replace(/ (\d{2})(\d{2})$/, " '$2");
    if (unit === "week") return monthDay(bucket.start);
    const date = new Date(bucket.start * 1000);
    if (all.length <= 16) return `${["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"][date.getDay()]} ${date.getDate()}`;
    return index === 0 || date.getDate() === 1 ? monthDay(bucket.start) : String(date.getDate());
}

/** Picks a clean hour step so the axis has 3-5 gridlines. */
export function hourTicks(maxSeconds: number): {step: number; ticks: number} {
    const steps = [0.25, 0.5, 1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 25, 30, 40, 50, 60, 80, 100, 120, 150, 200, 250, 300, 400, 500, 1000];
    const hours = maxSeconds / 3600;
    if (hours <= 0) return {step: 3600, ticks: 4};
    for (const step of steps) {
        const ticks = Math.ceil(hours / step);
        if (ticks <= 4) return {step: step * 3600, ticks: Math.max(ticks, 2)};
    }
    const step = Math.ceil(hours / 4 / 1000) * 1000;
    return {step: step * 3600, ticks: 4};
}

function tickLabel(seconds: number): string {
    if (seconds === 0) return "0";
    if (seconds < 3600) return `${Math.round(seconds / 60)}m`;
    return `${Math.round((seconds / 3600) * 100) / 100}h`;
}

function drawDailyTable(ctx: Ctx) {
    const {model, options} = ctx;
    const rows = model.buckets.filter(b => b.manual + b.activity > 0);
    if (!rows.length) return;
    const fmt = (s: number) => formatDuration(s, options.durationFormat);
    const label = (bucket: TimeBucket) =>
        model.bucketUnit === "day"
            ? dayLabel(bucket.start, options.dateFormat)
            : model.bucketUnit === "week"
              ? `Week of ${formatDate(bucket.start, options.dateFormat)}`
              : monthYear(bucket.start);
    const head = [model.bucketUnit === "day" ? "Date" : model.bucketUnit === "week" ? "Week" : "Month"];
    if (model.hasManual) head.push("Manual");
    if (model.hasActivity) head.push("Activity");
    if (model.hasManual && model.hasActivity) head.push("Total");
    const body = rows.map(bucket => {
        const row = [label(bucket)];
        if (model.hasManual) row.push(bucket.manual ? fmt(bucket.manual) : "–");
        if (model.hasActivity) row.push(bucket.activity ? fmt(bucket.activity) : "–");
        if (model.hasManual && model.hasActivity) row.push(fmt(bucket.manual + bucket.activity));
        return row;
    });
    const foot = ["Total"];
    if (model.hasManual) foot.push(fmt(model.totals.manual));
    if (model.hasActivity) foot.push(fmt(model.totals.activity));
    if (model.hasManual && model.hasActivity) foot.push(fmt(model.totals.total));

    ctx.y += 12;
    const style = tableStyle(ctx);
    const valueWidth = 84;
    ctx.autoTable(ctx.doc, {
        ...style,
        startY: ctx.y,
        head: [head.map(h => h.toUpperCase())],
        body,
        foot: [foot],
        alternateRowStyles: {fillColor: SURFACE.zebra},
        columnStyles: Object.fromEntries(head.map((_, i) => [i, i === 0 ? {cellWidth: "auto"} : {cellWidth: valueWidth, halign: "right"}])),
        didParseCell: data => {
            if (data.column.index > 0) data.cell.styles.halign = "right";
            const last = head.length - 1;
            if (data.section === "body" && data.column.index === last && head.length === 4) data.cell.styles.fontStyle = "bold";
            if (data.section === "body" && data.cell.raw === "–") data.cell.styles.textColor = INK.faint;
        },
    });
    afterTable(ctx);
}

/* --------------------------------------------------------- device breakdown */

export function drawDeviceBreakdown(ctx: Ctx) {
    const {model, options, theme} = ctx;
    if (!model.devices.length) return;
    const total = model.totals.activity;
    const fmt = (s: number) => formatDuration(s, options.durationFormat);
    sectionHeading(ctx, "Time by device", "Tracked activity only", 60);
    const noun = model.activitySource === "logs" ? "Log rows" : "Sessions";
    const style = tableStyle(ctx);
    ctx.autoTable(ctx.doc, {
        ...style,
        startY: ctx.y,
        head: [["DEVICE", noun.toUpperCase(), "TIME", "SHARE", ""]],
        body: model.devices.map(device => [pdfLine(device.name), String(device.items), fmt(device.seconds), percent(device.seconds, total), ""]),
        foot: model.devices.length > 1 ? [["Total", String(model.totals.activityItems), fmt(total), "100%", ""]] : undefined,
        alternateRowStyles: {fillColor: SURFACE.zebra},
        columnStyles: {
            0: {cellWidth: "auto", fontStyle: "bold"},
            1: {cellWidth: 60, halign: "right"},
            2: {cellWidth: 70, halign: "right"},
            3: {cellWidth: 50, halign: "right"},
            4: {cellWidth: Math.min(170, ctx.contentWidth * 0.3)},
        },
        didParseCell: data => {
            if (data.column.index >= 1 && data.column.index <= 3) data.cell.styles.halign = "right";
        },
        didDrawCell: data => {
            if (data.section !== "body" || data.column.index !== 4) return;
            const device = model.devices[data.row.index];
            const x = data.cell.x + 8;
            const w = data.cell.width - 14;
            const y = data.cell.y + data.cell.height / 2 - 3;
            fill(ctx, SURFACE.track);
            ctx.doc.roundedRect(x, y, w, 6, 1.5, 1.5, "F");
            fill(ctx, theme.accent);
            roundedBar(ctx, x, y, Math.max(2, (device.seconds / Math.max(total, 1)) * w), 6, 2, "right");
        },
    });
    afterTable(ctx);
}

/* ---------------------------------------------------------------- signature */

export function drawSignature(ctx: Ctx) {
    const {doc} = ctx;
    const height = 92;
    ctx.y += 30;
    ensureSpace(ctx, height);
    const left = ctx.margin.left;
    const gap = 36;
    const signatureWidth = (ctx.contentWidth - gap) * 0.62;
    const dateWidth = ctx.contentWidth - gap - signatureWidth;
    eyebrow(ctx, "Approval", left, ctx.y + 4);
    font(ctx, 8, "normal", INK.secondary);
    const preparedFor = pdfLine(ctx.options.pdf.preparedFor);
    doc.text(`I confirm the time in this report${preparedFor ? ` for ${preparedFor}` : ""} is accurate.`, left, ctx.y + 18);
    const lineY = ctx.y + 62;
    hairline(ctx, left, lineY, left + signatureWidth, INK.faint, 0.7);
    hairline(ctx, left + signatureWidth + gap, lineY, left + signatureWidth + gap + dateWidth, INK.faint, 0.7);
    font(ctx, 7.5, "normal", INK.muted);
    doc.text("Approved by (name and signature)", left, lineY + 11);
    doc.text("Date", left + signatureWidth + gap, lineY + 11);
    ctx.y = lineY + 16;
}

/* -------------------------------------------------------------- empty state */

export function drawEmptyState(ctx: Ctx) {
    const {doc, theme} = ctx;
    const height = 150;
    ensureSpace(ctx, height);
    const x = ctx.margin.left;
    const y = ctx.y + 6;
    fill(ctx, SURFACE.tile);
    doc.roundedRect(x, y, ctx.contentWidth, height, 6, 6, "F");
    const cx = x + ctx.contentWidth / 2;

    // Simple clock glyph.
    fill(ctx, theme.accentWash);
    doc.circle(cx, y + 44, 17, "F");
    ctx.doc.setDrawColor(...theme.accent);
    doc.setLineWidth(1.4);
    doc.circle(cx, y + 44, 9, "S");
    doc.line(cx, y + 44, cx, y + 38.5);
    doc.line(cx, y + 44, cx + 4, y + 46.5);

    font(ctx, 13, "bold");
    doc.text("No time recorded", cx, y + 86, {align: "center"});
    font(ctx, 8.5, "normal", INK.secondary);
    const message = `No entries were found for ${reportRange(ctx)} with the selected filters.`;
    doc.text(doc.splitTextToSize(message, ctx.contentWidth - 80) as string[], cx, y + 103, {align: "center"});
    font(ctx, 7.5, "normal", INK.muted);
    doc.text("Try widening the date range or including more categories, devices or datasets.", cx, y + 124, {align: "center"});
    ctx.y = y + height;
    ink(ctx, INK.primary);
    void tint;
}
